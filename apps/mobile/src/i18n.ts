const DICTS: Record<Lang, Dict> = { tr, en, de };

function detect(): Lang {
  try {
    const loc = Intl.DateTimeFormat().resolvedOptions().locale.slice(0, 2).toLowerCase();
    if (loc === "tr" || loc === "en" || loc === "de") return loc;
  } catch {
    /* Intl unavailable */
  }
  return "tr";
}

let current: Lang = detect();
const subs = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export async function loadLang() {
  try {
    const saved = await SecureStore.getItemAsync("nx.lang");
    if (saved === "tr" || saved === "en" || saved === "de") current = saved;
  } catch {
    /* keep detected */
  }
}

export function setLang(l: Lang) {
  current = l;
  SecureStore.setItemAsync("nx.lang", l).catch(() => {});
  subs.forEach((f) => f());
}

export function t(key: TKey, vars?: Record<string, string | number>): string {
  let s: string = DICTS[current][key] ?? tr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Re-renders the calling component when the language changes. */
export function useT() {
  const [, force] = useState(0);
  useEffect(() => {
    const f = () => force((x) => x + 1);
    subs.add(f);
    return () => {
      subs.delete(f);
    };
  }, []);
  return t;
}
